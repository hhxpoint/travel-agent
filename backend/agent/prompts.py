def get_chat_history_prompt(history: list) -> str:
    """构建包含历史对话的prompt"""
    if not history:
        return ""
    
    history_text = "\n\n## 历史对话记录：\n"
    for msg in history[-10:]:  # 只保留最近10条
        role = "用户" if msg["role"] == "user" else "助手"
        history_text += f"{role}: {msg['content']}\n"
    return history_text
